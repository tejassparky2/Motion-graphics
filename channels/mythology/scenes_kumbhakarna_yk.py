def dust(c, pt, stamp):
    """Dust and a jingle of light where a foot stamped."""
    if stamp <= 0.01:
        return
    fx, fy = Y.to_user(c, pt)
    for k in range(7):
        a = math.pi * (0.1 + 0.8 * k / 6)
        d = 40 + 150 * (1 - stamp)
        Y.sparkle(c, fx - d * math.cos(a), fy - 10 - d * 0.5 * math.sin(a), 20 * stamp, stamp)


def trail(c, t, pts, a=1.0, n=10):
    """A trail of light (sparkles) along a list of recent positions (newest first)."""
    for i, (x, y) in enumerate(pts[:n]):
        u = i / max(1, n - 1)
        Y.sparkle(c, x, y, (22 - 14 * u) * a, a * (1 - 0.85 * u))
    if pts:
        Y.glow(c, pts[0][0], pts[0][1], 110, 0.45 * a, C.SR_GLOW)


def arc_pos(u, p0, p1, lift=200.0):
    u = clamp(u)
    e = ease(u)
    return p0[0] + (p1[0] - p0[0]) * e, p0[1] + (p1[1] - p0[1]) * e - lift * math.sin(math.pi * e)


def stars_round(c, t, x, y, r, a=1.0):
    """Little dizzy stars circling a head."""
    for i in range(5):
        ang = t * 3.2 + i * 2 * math.pi / 5
        sx, sy = x + r * math.cos(ang), y + 0.35 * r * math.sin(ang)
        Y.glow(c, sx, sy, 50, 0.5 * a, (1.0, 0.85, 0.3))
        Y.sparkle(c, sx, sy, 38, a, (1.0, 0.92, 0.5))


