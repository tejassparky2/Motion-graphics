def shot_starts(tl):
    st = getattr(tl, "_ky_starts", None)
    if st is None:
        st = []
        for k, (bid, name, _) in enumerate(SHOTS):
            if k == 0:
                st.append(0.0)
                continue
            s = T(tl, bid) if name is None else cues(tl, bid)[name] - CUT_LEAD
            st.append(max(s, st[-1] + MIN_SHOT))
        tl._ky_starts = st
    return st


def shot_at(t, tl):
    st = shot_starts(tl)
    k = max(i for i, s in enumerate(st) if t >= s)
    return k, st[k], st[k + 1] if k + 1 < len(st) else tl.total


def draw(cr, t, tl):
    k, t0, t1 = shot_at(t, tl)
    cr.save()
    cr.set_line_join(cairo.LINE_JOIN_ROUND)
    SHOTS[k][2](cr, t, tl, t0, t1)
    cr.restore()
    if k > 0 and t - t0 < 0.2:                       # the lamps dip for a moment on a scene change
        cr.set_source_rgba(0.02, 0.01, 0.0, 0.45 * (1 - (t - t0) / 0.2))
        cr.paint()


def sfx(tl):
    """(time, name, dur), sparse (owner, 8 Nov 2026: "only use sounds where necessary"): a damaru on the hook, a bell on
    Brahma's "so be it", shimmer as Saraswati appears, a hit as the elephants walk on him, a conch as Brahma appears,
    then (where they fit) shimmer as she sits on his tongue, a damaru on his "ayyo!", a bell on the closing question.
    Chosen in that order of importance, each at least SFX_MIN_GAP from every sound already kept (as
    render_myth.calm_sfx keeps them), so the list is what plays; the bed dips before the reveals stay."""
    c = {b: cues(tl, b) for b in CUES}
    want = [(0.0, "damaru", 0), (c["k9"]["A"], "bell", 0), (c["k6"]["SP"], "shimmer", 0), (c["k13"]["H"], "hit", 0),
            (c["k4"]["H"], "conch", 0), (c["k7"]["B"], "shimmer", 0), (c["k10"]["K"], "damaru", 0),
            (c["k14"]["Y"], "bell", 0)]
    kept = []
    for e in want:
        if e[1] in SFX_KEEP and all(abs(e[0] - k[0]) >= SFX_MIN_GAP for k in kept):
            kept.append(e)
    dips = [(c["k9"]["A"] - 0.3, "dip", 0.45), (c["k11"]["F"] - 0.3, "dip", 0.5), (c["k13"]["H"] - 0.3, "dip", 0.5)]
    return [(round(max(0.0, a), 3), n, d) for a, n, d in sorted(kept + dips)]
