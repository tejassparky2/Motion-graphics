KX, KFEET, KS = 540, 1860, 0.98     # the hook / callback stance


def kk_hook_pose(t, mood="fierce", op=0.95, sr=1.0, stamp_at=None, lid=0.0):
    sh, ln, hd = Y.sway(t, 1.0, 0.45)
    lift, bb, stamp = Y.step(t, stamp_at, 0.9, "R") if stamp_at is not None else (0.0, 0.0, 0.0)
    look = 0.5 * math.sin(t * 0.9)
    p = dict(mood=mood, gaze=(look, 0.25), turn=0.15 * look, head=hd * 0.6, lean=ln, shift=sh,
             armL=(0.9, -1.9, 0.6), armR=(0.9, -1.9, 0.6), handL="open", handR="open",
             bend=0.3 + 0.25 * bb + 0.04 * math.sin(t * 2.9), liftR=0.7 * lift, sash=-ln * 3, lid=lid,
             breathe=math.sin(t * 2.2), ky_mouth="open" if op > 0.02 else None, ky_open=op, ky_sr=sr)
    return p, stamp


def kk_seat(pose, x=KX, feet=KFEET, s=KS):
    """The tongue seat (world) for a pose."""
    hf = head_frame(x, feet, s, pose)
    return face_pt(hf, 0, seat_dy(pose.get("ky_open", 1.0)) - 12)


def sr_glow(c, t, pts, a=1.0, ring=0.0):
    if "sr" not in pts or a <= 0.01:
        return
    x, y = Y.to_user(c, pts["sr"])
    pulse = 0.5 + 0.5 * math.sin(t * 4.0)
    Y.glow(c, x, y, 120, (0.45 + 0.15 * pulse) * a, C.SR_GLOW)
    Y.sparks(c, t, x, y + 20, 60, 5, 0.8 * a, 0.5, seed=4)
    if ring > 0:
        C.red_ring(c, x, y + 6, 70, 62, ring, 8)


