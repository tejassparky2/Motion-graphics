def head(cr, t, t_in, t_out, small, big, t_big=None, y=150, ss=72, bs=152, big_col=Y.RED, small_col=Y.YEL):
    """A two-tier Kannada headline shown from t_in (big line at t_big) until t_out."""
    if t < t_in - 0.2 or (t_out is not None and t >= t_out):
        return
    a = 1.0 if t_out is None else 1 - clamp((t - (t_out - 0.18)) / 0.18)
    Y.kn_headline(cr, t, small, big, t_in - 0.1, t_in + 0.2 if t_big is None else t_big, y=y, small_size=ss,
                  big_size=bs, alpha=a, big_col=big_col, small_col=small_col, max_w=930)


