def walk(t, t_a, t_b, x_a, x_b, rate=2.2):
    """(x, liftL, liftR) of an actor walking from x_a to x_b between t_a and t_b."""
    u = clamp((t - t_a) / max(0.1, t_b - t_a))
    x = x_a + (x_b - x_a) * ease(u)
    if 0 < u < 1:
        ph = (t - t_a) * rate * math.pi
        return x, max(0.0, math.sin(ph)) * 0.5, max(0.0, -math.sin(ph)) * 0.5
    return x, 0.0, 0.0


