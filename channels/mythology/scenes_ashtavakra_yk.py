def shot_at(t, tl):
    """(index, start, end) of the shot showing at t: each runs from its line's start (a moment early) to the next
    shot's start (cached on the timeline under _ay_shots)."""
    cache = getattr(tl, "_ay_shots", None)
    if cache is None:
        starts = [0.0]
        for bid, _ in SHOTS[1:]:
            starts.append(max(T(tl, bid) - 0.12, starts[-1] + 0.5))
        cache = tl._ay_shots = starts
    k = 0
    for i, s in enumerate(cache):
        if t >= s:
            k = i
    return k, cache[k], cache[k + 1] if k + 1 < len(cache) else tl.total


def draw(cr, t, tl):
    k, t0, t1 = shot_at(t, tl)
    cr.save()
    cr.set_line_join(cairo.LINE_JOIN_ROUND)
    SHOTS[k][1](cr, t, tl, t0, t1)
    cr.restore()
    if k > 0 and t - t0 < 0.22:                         # the lamps dip for a moment on a change of scene
        cr.set_source_rgba(0.02, 0.01, 0.0, 0.4 * (1 - (t - t0) / 0.22))
        cr.paint()


def sfx(tl):
    """(time, name, dur), sparse (owner, 8 Nov 2026: "only use sounds where necessary"): a damaru on the hook, a conch
    at the father's curse, a hit as the little boy wins, shimmer as his body becomes straight, a bell on the closing
    question; then, only where they fit, shimmer at the twist (all alive with the water god) and a bell at the name.
    Chosen in that order, each at least SFX_MIN_GAP from every sound already kept (as render_myth.calm_sfx keeps
    them), so this list is what plays (about 6 sounds); the bed dips before the reveals."""
    c = {b: cues(tl, b) for b in CUES}
    t_str = c["a15"]["S"] - 0.1
    t_end = min(max(c["a16"]["F"], t_str + SFX_MIN_GAP + 0.05), tl["a16"].end - 0.05)
    t_name = min(max(c["a7"]["A"], c["a6"]["C"] + SFX_MIN_GAP + 0.05), tl["a7"].end)    # the name (or its meaning)
    want = [(0.0, "damaru", 0), (c["a6"]["C"], "conch", 0), (c["a13"]["Wn"], "hit", 0), (t_str, "shimmer", 0),
            (t_end, "bell", 0), (c["a14"]["D"], "shimmer", 0), (t_name, "bell", 0), (c["a12"]["K"], "bell", 0)]
    kept = []
    for e in want:
        if e[1] in SFX_KEEP and all(abs(e[0] - k[0]) >= SFX_MIN_GAP for k in kept):
            kept.append(e)
    dips = [(c["a6"]["C"] - 0.3, "dip", 0.45), (c["a12"]["A"] - 0.3, "dip", 0.5), (c["a13"]["Wn"] - 0.35, "dip", 0.5),
            (c["a14"]["E"] - 0.3, "dip", 0.5), (t_str - 0.3, "dip", 0.45)]
    return [(round(max(0.0, a), 3), n, d) for a, n, d in sorted(kept + dips)]
