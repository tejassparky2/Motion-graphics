TRAY = (0.40, -2.05, 0.80)            # forearms up and out, palms flat and facing up, like holding a lamp


def hook_pose(t, raise_=0.0, stamp_t=None, mood="wonder"):
    sh, ln, hd = Y.sway(t, 1.0, 0.45)
    lift, bend_b, stamp = Y.step(t, stamp_t, 1.0, "R") if stamp_t is not None else (0.0, 0.0, 0.0)
    arm = mix(TRAY, (0.75, -2.15, 1.0), raise_)
    look = 0.7 * math.sin(t * 0.9)
    p = dict(mood=mood, gaze=(look, 0.75 - 0.5 * raise_), lid=0.25 - 0.2 * raise_, turn=0.25 * look,
             head=0.04 * look + hd * 0.6, lean=ln, shift=sh, armL=arm, armR=arm, handL="open", handR="open",
             bend=0.32 + 0.25 * bend_b + 0.05 * math.sin(t * 2.9), liftR=0.75 * lift, sash=-ln * 3,
             tail=0.12 * math.sin(t * 1.1), breathe=math.sin(t * 2.2))
    return p, stamp


def palm_lights(c, t, pts, a=1.0, size=1.0, raise_=0.0, flick=0.0, things=(None, None), sun_p=0.0, sea_p=0.0):
    """The golden lights floating over his palms (the hook and the callback). things[k] = 'sun' / 'sea' turns that
    light into a little painted sun / sea as sun_p / sea_p go 0 -> 1."""
    face = Y.to_user(c, pts["face"])
    pul = 0.5 + 0.5 * math.sin(t * 4.2)
    Y.glow(c, face[0], face[1] + 40, 230, (0.12 + 0.06 * pul + 0.1 * raise_) * a, (1.0, 0.75, 0.35))
    for k, hn in enumerate(("handL", "handR")):
        hx, hy = Y.to_user(c, pts[hn])
        ox, oy = hx, hy - 58 - 8 * math.sin(t * 2.5 + k)
        r = (30 + 5 * math.sin(t * 4.2 + k * 1.3) + 8 * raise_) * size
        aa = a * (1 - flick)
        thing = things[k]
        q = (sun_p if thing == "sun" else sea_p if thing == "sea" else 0.0)
        if thing and q > 0:
            oy -= 30 * q
            if thing == "sun":
                C.sun_disc(c, t, ox, oy, 46 * (0.4 + 0.6 * back(clamp(q), 2.0)), 0.0, clamp(q * 2), 0.8)
            else:
                C.ocean_disc(c, t, ox, oy, 52 * (0.4 + 0.6 * back(clamp(q), 2.0)), clamp(q * 2))
            aa *= 1 - clamp(q * 2)
        if aa > 0.01:
            Y.rays(c, t + k, ox, oy, r * 1.1, r * 4.2, (0.35 + 0.15 * pul) * aa, 14)
            Y.orb(c, t + k * 0.5, ox, oy, r, aa)
            Y.sparks(c, t, ox, oy, 70, 6, 0.8 * aa, 0.55, seed=k * 3)


def s_hook(cr, t, tl, t0, t1, z):
    c = cues(tl, "h1")
    S, B, N = c["S"], c["B"], c["N"]
    raise_ = prog(t, S - 0.15, 0.5) * (1 - prog(t, N, 0.5))
    p, stamp = hook_pose(t, raise_, S - 0.62)
    drain = ease(prog(t, N + 0.1, 1.0))
    flick = 0.0
    if B <= t < B + 0.7:
        flick = 0.65 * (0.5 + 0.5 * math.sin((t - B) * 38)) * (1 - (t - B) / 0.7)
    if t >= N:
        p.update(mood="sad", gaze=(0.85, -0.9), turn=0.35, head=0.06 + 0.02 * math.sin(t * 2), lid=0.0)
        arm = mix(TRAY, (0.30, -1.6, 0.6), drain)
        p.update(armL=arm, armR=arm)

    def extra(c_, pts):
        pt = pts[0]
        palm_lights(c_, t, pt, 1.0 - drain, 1.0 - 0.6 * drain, raise_, flick)
        if drain > 0.01:                                # the light trickling away
            for k, hn in enumerate(("handL", "handR")):
                hx, hy = Y.to_user(c_, pt[hn])
                for i in range(5):
                    u = (t * 0.9 + i / 5 + k * 0.1) % 1
                    Y.sparkle(c_, hx - 30 + 15 * i, hy + 20 + 260 * u * u, 14 * (1 - u), (1 - u) * (1 - drain) * 1.4)
        if stamp > 0.01:                                # dust and a jingle of light where the foot stamped
            fr = Y.to_user(c_, pt["footR"])
            for k in range(7):
                a = math.pi * (0.1 + 0.8 * k / 6)
                d = 40 + 140 * (1 - stamp)
