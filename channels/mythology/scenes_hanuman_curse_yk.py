def heads(cr, t, seq, y=150, ss=72, bs=150, max_w=960):
    """Two-tier headlines in time order: seq = [(t_small, small, t_big, big), ...]. The newest started one shows;
    the one before it fades out quickly (a kept small line stays put and only the big line changes)."""
    cur = prev = None
    for e in seq:
        if t >= e[0]:
            prev, cur = cur, e
    if cur is None:
        return None
    ts, small, tb, big = cur
    same = prev is not None and prev[1] == small
    if prev is not None and not same:
        if t - ts < 0.1:                                # the old one goes out first, then the new one pops in
            Y.kn_headline(cr, 99.0, prev[1], prev[3], -9, -9 if prev[3] else 1e9, y=y, small_size=ss, big_size=bs,
                          max_w=max_w, alpha=1 - (t - ts) / 0.1)
        ts += 0.1
        tb = max(tb, ts + 0.08)
    return Y.kn_headline(cr, t, small, big, -9 if same else ts, tb if big else 1e9, y=y, small_size=ss, big_size=bs,
                         max_w=max_w)


def actor(look, x, feet, s, pose, t, flip=False, shadow=0.5, alpha=1.0, extra=None):
    """One actor standing on the stage: a floor shadow, the figure, then extra(c, pts) drawn in the same layer."""
    def fn(c):
        if shadow:
            Y.floor_shadow(c, x + pose.get("shift", 0.0) * s, feet, 260 * s / 0.85, shadow * alpha)
        pts = Y.figure(c, look, x, feet, s, t, pose, flip, alpha)
        if extra:
            extra(c, pts)
        return pts
    return fn


def flyer(look, wx, wy, s, rot, pose, t, alpha=1.0):
    """An actor off the ground (flying, tumbling): the waist at (wx, wy), turned by rot."""
    def fn(c):
        c.save()
        c.translate(wx, wy)
        c.rotate(rot)
        pts = Y.figure(c, look, 0, 440 * s, s, t, pose, False, alpha)
        c.restore()
        return pts
    return fn


