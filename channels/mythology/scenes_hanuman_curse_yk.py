def glow_stars(cr, t, x, y, r, n=4, a=1.0):
    """Little stars circling a dazed head."""
    for k in range(n):
        ang = t * 3.2 + 2 * math.pi * k / n
        Y.sparkle(cr, x + r * math.cos(ang), y + 0.35 * r * math.sin(ang), 16 + 4 * math.sin(t * 5 + k), a)


