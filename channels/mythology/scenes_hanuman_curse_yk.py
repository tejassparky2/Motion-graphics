def smooth(u):
    u = clamp(u)
    return u * u * (3 - 2 * u)


def lin(t, t0, dur):
    """Plain linear 0..1 (poster.prog is already eased out; paths need an even pace)."""
    return clamp((t - t0) / dur) if dur > 0 else float(t >= t0)


def spin(t, t0, dur=0.8):
    """0..1 through one smooth full spin from t0 (0 outside it). Used instead of yaksha_kit.spin_phase, which jumps
    back from 0.875 to 0.5 halfway through."""
    u = (t - t0) / dur
    return smooth(u) if 0 < u < 1 else 0.0


def fly_path(u, p0=(330, 1480), p1=KID_UP[:2], lift=0.0, lo=0.2, hi=1.65):
    """The waist along a jump at u 0..1, and the angle he leans along it (kept between lo and hi, so he flies head
    first like a superhero and never dives upside down)."""
    (ax, ay), (bx, by) = p0, p1
    x = ax + (bx - ax) * u
    y = ay + (by - ay) * u - lift * 4 * u * (1 - u)
    dx = bx - ax
    dy = (by - ay) - lift * 4 * (1 - 2 * u)
    return x, y, min(hi, max(lo, math.atan2(dx, -dy)))


