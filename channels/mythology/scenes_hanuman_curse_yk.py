def _starts(tl):
    """Each shot's start (cached on the timeline under this module's own name)."""
    st = getattr(tl, "_hy_starts", None)
    if st is None:
        st = []
        for k, (bid, _, _) in enumerate(SHOTS):
            st.append(0.0 if k == 0 else max(T(tl, bid), st[-1] + MIN_SHOT))
        tl._hy_starts = st
    return st


def shot_at(t, tl):
    st = _starts(tl)
    k = max(i for i, s in enumerate(st) if t >= s)
    return k, st[k], st[k + 1] if k + 1 < len(st) else tl.total


def draw(cr, t, tl):
    k, t0, t1 = shot_at(t, tl)
    _, fn, (z0, z1) = SHOTS[k]
    z = z0 + (z1 - z0) * clamp((t - t0) / max(0.5, t1 - t0))
    cr.save()
    cr.set_line_join(cairo.LINE_JOIN_ROUND)
    fn(cr, t, tl, t0, t1, z)
    cr.restore()
    if k > 0 and t - t0 < 0.22:                         # the lamps dip for a moment on a scene change
        cr.set_source_rgba(0.02, 0.01, 0.0, 0.35 * (1 - (t - t0) / 0.22))
        cr.paint()


def sfx(tl):
    """(time, name, dur), sparse: a damaru on the hook, a single hit as Indra's vajra strikes, a conch as the sages
    say "you will forget", shimmer as Hanuman remembers, a bell on the closing question, then (only where they fit)
    a conch on the giant jump, shimmer on the gods' powers, a damaru as the child flies at the sun, a bell on the
    mid-story question and shimmer as the red sun appears. Chosen in THAT order, each at least SFX_MIN_GAP from every
    sound already kept (as render_myth.calm_sfx keeps them), so the list is what plays (6-7 sounds); the bed dips
    before the reveals stay."""
    c = {b: cues(tl, b) for b in CUES}
    want = [(0.0, "damaru", 0), (c["h5"]["J"], "hit", 0), (c["h9"]["F"], "conch", 0), (c["h14"]["R"], "shimmer", 0),
            (c["h16"]["H"], "bell", 0), (c["h15"]["L"] - 0.35, "conch", 0), (c["h7"]["P"], "shimmer", 0),
            (c["h4"]["U"], "damaru", 0), (c["h12q"]["W"], "bell", 0), (c["h3"]["R"], "shimmer", 0)]
    kept = []
    for e in want:
        if e[1] in SFX_KEEP and all(abs(e[0] - k[0]) >= SFX_MIN_GAP for k in kept):
            kept.append(e)
    dips = [(c["h5"]["J"] - 0.35, "dip", 0.5), (c["h9"]["F"] - 0.3, "dip", 0.45), (c["h14"]["R"] - 0.3, "dip", 0.5)]
    return [(round(max(0.0, a), 3), n, d) for a, n, d in sorted(kept + dips)]
