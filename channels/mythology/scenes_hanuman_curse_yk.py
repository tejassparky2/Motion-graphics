def sky_wheel(c_, t, t_a, dur, n=3):
    """The painted sun and moon racing across the thera, n days and nights in dur seconds; returns the night 0..1."""
    u = (t - t_a) / dur
    if not 0 < u < 1:
        return 0.0
    x0, y0, x1, y1 = C.FIELD
    ph = u * n
    k = int(ph)
    f = ph - k
    night = math.sin(math.pi * f) if k % 2 else 0.0
    c_.save()
    C.field_clip(c_)
    x = x0 - 80 + (x1 - x0 + 160) * f
    y = y0 + 330 - 230 * math.sin(math.pi * f)
    if k % 2 == 0:
        C.sun_disc(c_, t, x, y, 70, 0.0, 0.8)
    else:
        Y.glow(c_, x, y, 200, 0.4, (0.7, 0.8, 1.0))
        c_.new_path()                                   # a crescent moon
        c_.arc(x, y, 62, 0, 2 * math.pi)
        c_.new_sub_path()
        c_.arc_negative(x + 26, y - 14, 52, 2 * math.pi, 0)
        c_.set_fill_rule(cairo.FILL_RULE_EVEN_ODD)
        Y.ink_fill(c_, (0.98, 0.95, 0.80), 5.0)
        c_.set_fill_rule(cairo.FILL_RULE_WINDING)
    c_.restore()
    return night


