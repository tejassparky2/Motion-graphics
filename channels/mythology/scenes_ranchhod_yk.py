def out_a(t, t_out, d=0.18):
    """1 until t_out - d, then fading to 0 at t_out."""
    return 1.0 - prog(t, t_out - d, d)


def walk(t, t0, t1, x0, x1, period=0.64, amp=0.55):
    """Stepping across the stage from x0 to x1 between t0 and t1: (x, liftL, liftR, bob)."""
    u = clamp((t - t0) / max(0.01, t1 - t0))
    x = x0 + (x1 - x0) * (u * u * (3 - 2 * u))
    if t <= t0 or t >= t1:
        return x, 0.0, 0.0, 0.0
    ph = (t - t0) / period
    f = ph % 1.0
    lift = amp * math.sin(math.pi * f)
    side = int(ph) % 2
    return x, lift if side == 0 else 0.0, lift if side == 1 else 0.0, abs(math.sin(math.pi * f))


def puff(c, x, y, a, s=1.0):
    """A dust puff at a foot that has just stamped (a: 1 at the stamp, fading to 0)."""
    if a <= 0.02:
        return
    u = 1 - a
    for k in range(6):
        ang = math.pi * (0.08 + 0.84 * k / 5)
        d = (30 + 120 * u) * s
        c.new_path()
        c.arc(x - d * math.cos(ang), y - 4 - d * 0.35 * math.sin(ang), (14 + 22 * u) * s, 0, 2 * math.pi)
        c.set_source_rgba(0.80, 0.62, 0.42, 0.6 * a)
        c.fill()


def zzz(c, t, x, y, s=1.0, a=1.0, n=3):
    """Z's rising and growing from (x, y), drifting up and right."""
    if a <= 0.01:
        return
    for i in range(n):
        u = (t * 0.45 + i / n) % 1.0
        al = a * clamp(u * 4) * clamp((1 - u) * 3)
