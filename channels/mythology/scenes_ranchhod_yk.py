def compose(cr, t, actors, theme=("crimson", "sun"), zoom=(1.0, W / 2, 1150), behind=None, extra=None, ui=None,
            flash=0.0, musicians_at=None, shadow=True, light_strength=1.0, garland=True, dark=0.0, spot=None,
            white=0.0, sky_speed=0.0, sky_base=0.15, shake=(0.0, 0.0)):
    """Y.compose with a choice of thera: theme = (style, motif) of the kit, "cave" (inside the cave) or "hills" (the
    chase); dark = a night over everything (spot = (x, y, r) keeps a pool of light), white = a white flash."""
    z, zx, zy = zoom
    sx, sy = shake

    def apply(c):
        if sx or sy:
            c.translate(sx, sy)
        if z != 1.0:
            c.translate(zx, zy)
            c.scale(z, z)
            c.translate(-zx, -zy)
    cr.set_source_rgb(0.02, 0.015, 0.03)              # an opaque night first (a zoomed-out stage leaves edges)
    cr.paint()
    cr.save()
    apply(cr)
    if theme == "cave":
        C.cave_stage(cr, t, sky_speed, sky_base, garland)
    elif theme == "hills":
        C.hills_stage(cr, t, garland)
    else:
        Y.stage(cr, t, theme[0], theme[1], True, garland)
    if behind:
        behind(cr)
    if musicians_at is not None:
        for mx, ms, mflip in musicians_at:
            Y.musicians(cr, t, mx, Y.FLOOR_Y + 40, ms, mflip)
    m = cr.get_matrix()

    def draw_all(c):
        c.set_matrix(m)
        return [fn(c) for fn in actors]
    surf, pts = Y.layer(draw_all)
    cr.restore()
    if shadow:
        Y.cast_shadow(cr, surf)
    Y.paint_layer(cr, surf)
    cr.save()
    apply(cr)
    if extra:
        extra(cr, pts)
    Y.lamps(cr, t)
    cr.restore()
    Y.light(cr, t, light_strength, flash)
    if dark > 0.01:
        if spot:
            x, y, r = spot
            g = cairo.RadialGradient(x, y, r * 0.35, x, y, r)
            g.add_color_stop_rgba(0, 0.0, 0.0, 0.02, 0.0)
            g.add_color_stop_rgba(1, 0.0, 0.0, 0.02, dark)
            cr.set_source(g)
        else:
            cr.set_source_rgba(0.0, 0.0, 0.02, dark)
        cr.paint()
    C.white_flash(cr, white)
    if ui:
        ui(cr, pts)
    Y.finish(cr, t)
    return pts


