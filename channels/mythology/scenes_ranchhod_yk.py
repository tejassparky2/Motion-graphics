def _starts(tl):
    st = getattr(tl, "_rcy_shot_starts", None)
    if st is None:
        st = [0.0]
        for bid, *_ in SHOTS[1:]:
            st.append(max(T(tl, bid), st[-1] + 0.5))
        tl._rcy_shot_starts = st
    return st


def shot_at(t, tl):
    st = _starts(tl)
    k = max(i for i, s in enumerate(st) if t >= s)
    return k, st[k], st[k + 1] if k + 1 < len(st) else tl.total


def draw(cr, t, tl):
    k, t0, t1 = shot_at(t, tl)
    _, fn, (z0, z1), fy = SHOTS[k]
    z = z0 + (z1 - z0) * clamp((t - t0) / max(0.5, t1 - t0))
    cr.set_line_join(cairo.LINE_JOIN_ROUND)
    fn(cr, t, tl, T(tl, SHOTS[k][0]) if k else 0.0, t1, (z, W / 2, fy))
    if k > 0 and t - t0 < 0.22:                         # the lamps dip for a moment on a scene change
        cr.set_source_rgba(0.02, 0.01, 0.0, 0.35 * (1 - (t - t0) / 0.22))
        cr.paint()


def sfx(tl):
    """(time, name, dur), sparse (owner, 8 Nov 2026: "only use sounds where necessary"): a damaru on the hook and as
    the chase begins, shimmer as the gods' boon flies into Muchukunda, a hit on the kick, a conch on the twist
    ("ನೇರವಾಗಿ": the map of the run), a bell on the closing question. Chosen exactly as render_myth.calm_sfx keeps them
    (SFX_KEEP rank, then time, each at least SFX_MIN_GAP from every sound already kept), so the list returned is what
    plays; the bed dips before the white flash, the twist and the question."""
    c = {b: cues(tl, b) for b in CUES}
    want = [(c["rc15"]["N"], "conch", 0), (c["rc16"]["B"], "bell", 0), (c["rc10"]["V"] - 0.3, "shimmer", 0),
            (0.0, "damaru", 0), (c["rc8"]["t0"], "damaru", 0), (c["rc13"]["O"], "hit", 0)]
    rank = {n: i for i, n in enumerate(SFX_KEEP)}
    kept = []
    for e in sorted((e for e in want if e[1] in rank), key=lambda e: (rank[e[1]], e[0])):
        if all(abs(e[0] - k[0]) >= SFX_MIN_GAP for k in kept):
            kept.append(e)
    dips = [(c["rc8q"]["t0"] - 0.3, "dip", 0.4), (c["rc14"]["S"] - 0.35, "dip", 0.5),
            (c["rc15"]["N"] - 0.3, "dip", 0.45)]
    return [(round(max(0.0, a), 3), n, d) for a, n, d in sorted(kept + dips)]
