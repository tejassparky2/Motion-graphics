def pic_card(c, t, t_in, x, y, w, h, lines, pic=None, field=Y.CRIMSON, alpha=1.0, ring=0.0, rot=0.0, pic_h=0.55):
    """A painted card: gold frame, a coloured field, a picture in its upper part (pic(c, cx, cy, k) draws it centred at
    (cx, cy) at scale k) and Kannada lines [(text, size, colour), ...] in its lower part; a red ring when ring > 0."""
    q = clamp((t - t_in) / 0.4)
    if q <= 0 or alpha <= 0.01:
        return
    k = 0.6 + 0.4 * back(q, 1.8)
    c.save()
    c.translate(x, y)
    c.rotate(rot)
    c.scale(k, k)
    c.push_group()
    _rr(c, -w / 2 + 10, -h / 2 + 14, w, h, 22)
    c.set_source_rgba(0, 0, 0, 0.45)
    c.fill()
    _rr(c, -w / 2, -h / 2, w, h, 22)
    Y.ink_fill(c, Y.GOLD, 7.0)
    _rr(c, -w / 2 + 18, -h / 2 + 18, w - 36, h - 36, 14)
    Y.ink_fill(c, field, 5.0)
    if pic:
        c.save()
        _rr(c, -w / 2 + 18, -h / 2 + 18, w - 36, h - 36, 14)
        c.clip()
        pic(c, 0, -h / 2 + h * pic_h / 2 + 10, 1.0)
        c.restore()
    surfs = [Y.kn_surface(tx, int(sz), tuple(col), tuple(Y.INK), 6.0, None, 0.0) for tx, sz, col in lines]
    th = sum(s.get_height() for s in surfs) + 8 * (len(surfs) - 1)
    ytop = -h / 2 + h * pic_h if pic else -th / 2
    room = (h / 2 - 26 - ytop) if pic else th
    yy = ytop + max(0.0, (room - th) / 2)
    for s in surfs:
        f = min(1.0, (w - 70) / s.get_width())
        c.save()
        c.translate(0, yy + s.get_height() * f / 2)
        c.scale(f, f)
        c.set_source_surface(s, -s.get_width() / 2, -s.get_height() / 2)
        c.paint()
        c.restore()
        yy += s.get_height() * f + 8
    c.pop_group_to_source()
    c.paint_with_alpha(alpha * clamp(q * 3))
    c.restore()
    if ring > 0.01:
        M.red_ring(c, x, y, w * 0.62, h * 0.60, 1.0, 14, ring, rot - 0.04)


def split_word(c, t, t_in, parts, cx, y, size=200, max_w=900):
    """A big word in parts of different colours [(text, colour, alpha), ...], popping in at t_in; top at y.
    Returns each part's box."""
    q = clamp((t - t_in) / 0.38)
    if q <= 0:
        return []
    surfs = [Y.kn_surface(tx, int(size), tuple(col), tuple(Y.CREAM), 9.0, tuple(Y.INK), 7.0) for tx, col, _ in parts]
    gap = 50.0
    tw = sum(s.get_width() for s in surfs) + gap * (len(surfs) - 1)
    hh = max(s.get_height() for s in surfs)
    fit = min(1.0, max_w / tw)
    k = fit * (0.55 + 0.45 * back(q, 2.2))
    c.save()
    c.translate(cx, y + hh * fit / 2)
    c.scale(k, k)
    xx = -tw / 2
    boxes = []
    for s, (_, _, a) in zip(surfs, parts):
        c.set_source_surface(s, xx, -hh / 2 + (hh - s.get_height()) / 2)
        c.get_source().set_filter(cairo.FILTER_GOOD)
        c.paint_with_alpha(clamp(q * 2.5) * a)
        boxes.append((cx + xx * k, y + hh * fit / 2 - hh / 2 * k, s.get_width() * k, hh * k))
        xx += s.get_width() + gap
    c.restore()
    return boxes


def down_arrow(c, x, y0, y1, p, col=Y.CREAM):
    if p <= 0.01:
        return
    ye = y0 + (y1 - y0) * ease(p)
    Y.stroke(c, [(x, y0), (x, ye)], 20, Y.INK, smooth=False)
    Y.stroke(c, [(x, y0), (x, ye)], 10, col, smooth=False)
    Y.shape(c, [(x - 26, ye - 12), (x + 26, ye - 12), (x, ye + 22)], col, 5.0, smooth=False)


def note(c, x, y, s=1.0, a=1.0):
    """A painted music note (the flute's tune)."""
    if a <= 0.01:
        return
    c.save()
    c.translate(x, y)
    c.scale(s, s)
    c.push_group()
    Y.stroke(c, [(14, 0), (14, -64), (40, -52)], 7, Y.INK, smooth=False)
    Y.stroke(c, [(14, 0), (14, -64), (40, -52)], 3.5, Y.CREAM, smooth=False)
    Y.oval(c, 2, 2, 16, 12, Y.CREAM, 4.0, rot=-0.4)
    c.pop_group_to_source()
    c.paint_with_alpha(a)
    c.restore()


def mini(c, look, x, feet, s, t, p, ang=0.0):
    """A small figure (for cards, clouds), drawn straight onto the frame."""
    if ang:
        c.save()
        c.translate(x, feet)
        c.rotate(ang)
        pts = Y.figure(c, look, 0, 0, s, t, p)
        c.restore()
        return pts
    return Y.figure(c, look, x, feet, s, t, p)


