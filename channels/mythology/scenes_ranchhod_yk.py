CAVE_X, CAVE_S = 850, 1.15
OMEGA = 2 * math.pi / 2.3            # one lap of the stage every 2.3 s
LAG = 1.55                           # Kalayavana's place on the circle behind Krishna (radians): just out of reach


def wrap(a):
    return (a + math.pi) % (2 * math.pi) - math.pi


def chase_pos(t, c, lag=0.0):
    """Where a runner is in the chase: round and round the stage (a Yakshagana circle: front = big and low, back =
    small and high), then, from Te, straight to the cave.
    Returns (x, feet, scale k, depth, direction, phase, gone 0..1).
    lag = how far behind Krishna (radians)."""
    A, V = c["A"], c["V"]
    te = V - 0.45 + lag / OMEGA                      # this runner leaves the circle at the front, heading right
    shrink = ease(prog(t, A - 0.2, 0.6))             # the circle tightens to the left as the cave appears
    cx = mix(540, 400, shrink)
    rx = mix(360, 210, shrink)
    if t < te:
        ph = OMEGA * (t - te)
        x = cx + rx * math.sin(ph)
        d = math.cos(ph)
        return x, 1760 + 70 * d, 0.86 + 0.18 * d, d, (1 if math.cos(ph) >= 0 else -1), ph, 0.0
    u = clamp((t - te) / 0.6)
    x = mix(cx, CAVE_X, u)
    return x, 1830, 1.04, 1.0, 1, 0.0, prog(t, te + 0.45, 0.3)


