def draupadi_hook_pose(t, t0, c):
    """Draupadi in the hook (and again in the callback at its first frame): upright, calm, a gentle sway; on "ಯಾವತ್ತೂ"
    she shakes her head and wags a raised palm (no); on the stamp she dips, with dust at her feet."""
    no = prog(t, c["K"] - 0.1, 0.3) * (1 - prog(t, c["L"] + 0.2, 0.4)) if c else 0.0
    shake = 0.09 * math.sin((t - c["K"]) * 13) * math.exp(-1.8 * max(0.0, t - c["K"])) if c and t > c["K"] else 0.0
    lift, bb, stamp = Y.step(t, c["N"] - 0.5, 0.9, "R") if c else (0, 0, 0)
    wag = 0.35 * math.sin((t - c["K"]) * 12) * math.exp(-1.2 * max(0.0, t - c["K"])) if c and t > c["K"] else 0.0
    arm_r = mix((0.18, 0.35, 0.0), (0.32, -2.6, wag), no)
    p = base_pose(t, 0.5, mood="calm", gaze=(0.0, 0.1), turn=0.0, armL=(0.14, 0.5, 0.0), armR=arm_r,
                  handR="open", bend=0.25 + 0.25 * bb)
    p["head"] += shake
    return p, stamp


