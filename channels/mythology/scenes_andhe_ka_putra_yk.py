def stamp_dust(c, t, foot, stamp, k=7):
    """Sparks of dust where a foot stamped."""
    if stamp <= 0.01:
        return
    for i in range(k):
        a = math.pi * (0.1 + 0.8 * i / (k - 1))
        d = 40 + 140 * (1 - stamp)
        Y.sparkle(c, foot[0] - d * math.cos(a), foot[1] - 10 - d * 0.5 * math.sin(a), 18 * stamp, stamp)


