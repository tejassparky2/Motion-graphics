def compose(cr, t, actors, theme=("crimson", "sun"), zoom=(1.0, W / 2, 1150), behind=None, extra=None, ui=None,
            flash=0.0, musicians_at=None, shadow=True, light_strength=1.0, garland=True):
    """Y.compose with a choice of thera: theme = (style, motif) of the kit, or "palace" (Maya's crystal hall)."""
    z, zx, zy = zoom

    def apply(c):
        if z != 1.0:
            c.translate(zx, zy)
            c.scale(z, z)
            c.translate(-zx, -zy)
    cr.set_source_rgb(0.02, 0.015, 0.03)              # an opaque night first (a zoomed-out stage leaves edges)
    cr.paint()
    cr.save()
    apply(cr)
    if theme == "palace":
        C.palace_stage(cr, t, garland)
    else:
        Y.stage(cr, t, theme[0], theme[1], True, garland)
    if behind:
        behind(cr)
    if musicians_at is not None:
        mx, ms, mflip = musicians_at
        Y.musicians(cr, t, mx, Y.FLOOR_Y + 40, ms, mflip)
    m = cr.get_matrix()

    def draw_all(c):
        c.set_matrix(m)
        return [fn(c) for fn in actors]
    surf, pts = Y.layer(draw_all)
    cr.restore()
    if shadow:
        Y.cast_shadow(cr, surf)
    Y.paint_layer(cr, surf)
    cr.save()
    apply(cr)
    if extra:
        extra(cr, pts)
    Y.lamps(cr, t)
    cr.restore()
    Y.light(cr, t, light_strength, flash)
    if ui:
        ui(cr, pts)
    Y.finish(cr, t)
    return pts


