def _sick_spots():
    """For each cloud over the world: the toy person on the rim nearest under it."""
    gx, gy, gr = WORLD14
    xs = (300, 450, 630, 780)
    used, out = set(), []
    for x in xs:
        best, bd = None, 1e9
        for i, (m, p, kd, ci) in enumerate(C.SPOTS):
            if m != "rim" or kd not in C.PEOPLE or i in used:
                continue
            sx, sy, _ = C.spot_xy(i, gx, gy, gr)
            d = abs(sx - x) + 0.2 * abs(sy - (gy - gr))
            if d < bd:
                best, bd = i, d
        used.add(best)
        out.append(best)
    return out


