def sfx(tl):
    """(time, name, dur), sparse (owner, 8 Nov 2026: "only use sounds where necessary"): a damaru on the hook, a conch
    as Shiva appears, shimmer as the tears turn into diseases (the twist), a bell on the closing question, then (only
    where they fit) shimmer as the girl comes out of Brahma and a hit as the fire bursts out. Chosen exactly as
    render_myth.calm_sfx keeps them (SFX_KEEP rank, then time, each at least SFX_MIN_GAP from every sound already
    kept), so the list returned is what plays (about 6 sounds); the bed dips before the reveals stay."""
    c = {b: cues(tl, b) for b in CUES}
    want = [(0.0, "damaru", 0), (c["mr7"]["S"], "conch", 0), (c["mr14"]["R"], "shimmer", 0),
            (c["mr17"]["P"], "bell", 0), (c["mr8"]["K"], "shimmer", 0), (c["mr6"]["F"], "hit", 0),
            (c["mr3"]["S"], "shimmer", 0), (c["mr12"]["Y"], "damaru", 0)]
    rank = {n: i for i, n in enumerate(SFX_KEEP)}
    kept = []
    for e in sorted((e for e in want if e[1] in rank), key=lambda e: (rank[e[1]], e[0])):
        if all(abs(e[0] - k[0]) >= SFX_MIN_GAP for k in kept):
            kept.append(e)
    dips = [(c["mr8"]["K"] - 0.3, "dip", 0.45), (c["mr14"]["R"] - 0.35, "dip", 0.5),
            (c["mr16c"]["F"] - 0.3, "dip", 0.45)]
    return [(round(max(0.0, a), 3), n, d) for a, n, d in sorted(kept + dips)]
