def twist_clouds(t, R):
    """[(x, y, scale, alpha)] of the five clouds rising out of the palms from R."""
    px, py, ps = PALMS
    out = []
    for k, (gx, gy) in enumerate(CLOUD_GO):
        u = clamp((t - (R + 0.15 + 0.16 * k)) / 0.75)
        if u <= 0:
            continue
        e = ease(u)
        x0 = px + (k - 2) * 70
        x = x0 + (gx - x0) * e
        y = (py + 30) + (gy - py - 30) * e
        out.append((x, y, 0.2 + 0.8 * e, clamp(u * 4)))
    return out


