def cam_to(px, py, z, sx, sy):
    """The zoom (z, zx, zy) that scales by z and puts world point (px, py) at screen (sx, sy)."""
    if abs(z - 1.0) < 1e-4:
        return (1.0, W / 2, H * 0.6)
    return (z, (sx - px * z) / (1 - z), (sy - py * z) / (1 - z))


def push(t, t0, t1, k=0.03, at=(540, 1150)):
    """The slow push-in every shot has."""
    u = clamp((t - t0) / max(0.5, t1 - t0))
    return cam_to(at[0], at[1], 1.0 + k * u, at[0], at[1])


def compose(cr, t, actors, theme=("crimson", "sun"), zoom=(1.0, W / 2, 1150), behind=None, extra=None, ui=None,
            flash=0.0, musicians_at=None, shadow=True, light_strength=1.0, garland=True, front=None):
    """Y.compose with a choice of thera: (style, motif) of the kit, or "heaven" (the gold svarga thera). front(cr):
    things in front of the actors but under the lamps (water cloth)."""
    z, zx, zy = zoom

    def apply(c):
        if z != 1.0:
            c.translate(zx, zy)
            c.scale(z, z)
            c.translate(-zx, -zy)
    cr.set_source_rgb(0.02, 0.015, 0.03)
    cr.paint()
    cr.save()
    apply(cr)
    if theme == "heaven":
        Y.stage(cr, t, "crimson", "rays", True, garland)
        C.heaven_field(cr)
    else:
        Y.stage(cr, t, theme[0], theme[1], True, garland)
    if behind:
        behind(cr)
    if musicians_at is not None:
        mx, ms, mflip = musicians_at
        Y.musicians(cr, t, mx, Y.FLOOR_Y + 40, ms, mflip)
    m = cr.get_matrix()

    def draw_all(c):
        c.set_matrix(m)
        return [fn(c) for fn in actors]
    surf, pts = Y.layer(draw_all)
    cr.restore()
    if shadow:
        Y.cast_shadow(cr, surf)
    Y.paint_layer(cr, surf)
    cr.save()
    apply(cr)
    if extra:
        extra(cr, pts)
    if front:
        front(cr)
    Y.lamps(cr, t)
    cr.restore()
    Y.light(cr, t, light_strength, flash)
    if ui:
        ui(cr, pts)
    Y.finish(cr, t)
    return pts


