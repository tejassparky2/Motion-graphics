def _starts(tl):
    st = getattr(tl, "_sny_starts", None)
    if st is None:
        st = []
        for k, (bid, name, _) in enumerate(SHOTS):
            if k == 0:
                st.append(0.0)
                continue
            s = T(tl, bid) if name is None else cues(tl, bid)[name] - CUT_LEAD
            st.append(max(s, st[-1] + MIN_SHOT))
        tl._sny_starts = st
    return st


def shot_at(t, tl):
    st = _starts(tl)
    k = max(i for i, s in enumerate(st) if t >= s)
    return k, st[k], st[k + 1] if k + 1 < len(st) else tl.total


def draw(cr, t, tl):
    k, t0, t1 = shot_at(t, tl)
    cr.save()
    cr.set_line_join(cairo.LINE_JOIN_ROUND)
    SHOTS[k][2](cr, t, tl, t0, t1)
    cr.restore()
    if k > 0 and t - t0 < 0.2:                       # the lamps dip for a moment on a scene change
        cr.set_source_rgba(0.02, 0.01, 0.0, 0.45 * (1 - (t - t0) / 0.2))
        cr.paint()


def sfx(tl):
    """(time, name, dur), sparse (owner, 8 Nov 2026: "only use sounds where necessary"): a conch as the tongue splits,
    a bell on the closing question, shimmer as the pot of amrit shows in heaven, a damaru on the hook, a hit as the
    guards are blown away, then (where they fit) shimmer as the darbhe turns holy and a damaru as Indra lifts the pot.
    Chosen as render_myth.calm_sfx keeps them (SFX_KEEP rank, then time, each at least SFX_MIN_GAP from every sound
    already kept), so the list is what plays; the bed dips before the reveals stay."""
    c = {b: cues(tl, b) for b in CUES}
    want = [(c["sn15"]["S"] - 0.1, "conch", 0), (c["sn17"]["S"], "bell", 0), (c["sn7"]["H"], "shimmer", 0),
            (0.0, "damaru", 0), (c["sn8"]["G"] + 0.15, "hit", 0), (c["sn16"]["V"], "shimmer", 0),
            (c["sn13"]["L"], "damaru", 0), (c["sn10"]["U"], "shimmer", 0)]
    rank = {n: i for i, n in enumerate(SFX_KEEP)}
    kept = []
    for e in sorted((e for e in want if e[1] in rank), key=lambda e: (rank[e[1]], e[0])):
        if all(abs(e[0] - k[0]) >= SFX_MIN_GAP for k in kept):
            kept.append(e)
    dips = [(c["sn13"]["H"] - 0.3, "dip", 0.45), (c["sn15"]["S"] - 0.4, "dip", 0.5)]
    return [(round(max(0.0, a), 3), n, d) for a, n, d in sorted(kept + dips)]
