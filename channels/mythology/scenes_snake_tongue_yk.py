def cues(tl, bid):
    """{name: time} for a line (cached on the timeline as _sny_cues)."""
    cache = getattr(tl, "_sny_cues", None)
    if cache is None:
        cache = tl._sny_cues = {}
    if bid not in cache:
        out = {"t0": T(tl, bid)}
        for name, word, frac, cons in CUES[bid]:
            v = cue(tl, bid, word, frac)
            for after, gap in cons:
                v = max(v, out[after] + gap)
            out[name] = v
        out["end"] = tl[bid].end
        cache[bid] = out
    return cache[bid]


