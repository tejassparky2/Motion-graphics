def _at(tl, bid, word, n=1):
    """Start of the n-th word of line bid containing `word` (spoken words if the take has them, else the text)."""
    b = tl[bid]
    if b.words:
        hits = [b.start + s for w, s, _ in b.words if word in w]
        if len(hits) >= n:
            return hits[n - 1]
    i = -1
    for _ in range(n):
        i = b.text.find(word, i + 1)
        if i < 0:
            raise KeyError(word)
    return b.start + b.dur * i / max(1, len(b.text))


def cue(tl, bid, word, frac):
    w, n = (word if isinstance(word, tuple) else (word, 1))
    try:
        return _at(tl, bid, w, n)
    except (KeyError, ValueError):
        MISSES.add((bid, w, n))
        return T(tl, bid, frac)


