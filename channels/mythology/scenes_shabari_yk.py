def out_a(t, t_out, d=0.18):
    """1 until t_out - d, then fading to 0 at t_out."""
    return 1.0 - prog(t, t_out - d, d)


def walk(t, t0, t1, x0, x1, period=0.6, amp=0.5):
    """Stepping across the stage from x0 to x1 between t0 and t1: (x, liftL, liftR)."""
    u = clamp((t - t0) / max(0.01, t1 - t0))
    x = x0 + (x1 - x0) * (u * u * (3 - 2 * u))
    if t <= t0 or t >= t1:
        return x, 0.0, 0.0
    ph = (t - t0) / period
    f = ph % 1.0
    lift = amp * math.sin(math.pi * f)
    side = int(ph) % 2
    return x, lift if side == 0 else 0.0, lift if side == 1 else 0.0


def nod(t, t0, n=2, amp=0.10, dur=0.7):
    """A gentle nod (head angle) starting at t0."""
    u = (t - t0) / dur
    if not 0 < u < 1:
        return 0.0
    return amp * math.sin(math.pi * 2 * n * u) * (1 - u)


def shake(t, t0, amp=0.12, dur=0.9):
    """Shaking the head no (turn and head angle) starting at t0."""
    u = (t - t0) / dur
    if not 0 < u < 1:
        return 0.0
    return amp * math.sin(u * 6 * math.pi) * (1 - u)


def pulse(t, t0, dur=0.35):
    if t < t0:
        return 0.0
    return math.exp(-(t - t0) / dur * 3.0)


