def compose(cr, t, actors, theme=("crimson", "sun"), zoom=(1.0, W / 2, 1150), behind=None, extra=None, ui=None,
            flash=0.0, musicians_at=None, shadow=True, light_strength=1.0, garland=True, dim=0.0):
    """Y.compose with the zoom applied to the set and the actors, effects over them, text on top. dim darkens the
    whole stage (night) under the effects and the text."""
    z, zx, zy = zoom

    def apply(c):
        if z != 1.0:
            c.translate(zx, zy)
            c.scale(z, z)
            c.translate(-zx, -zy)
    cr.set_source_rgb(0.02, 0.015, 0.03)
    cr.paint()
    cr.save()
    apply(cr)
    Y.stage(cr, t, theme[0], theme[1], True, garland)
    if behind:
        behind(cr)
    if musicians_at is not None:
        mx, ms, mflip = musicians_at
        Y.musicians(cr, t, mx, Y.FLOOR_Y + 40, ms, mflip)
    m = cr.get_matrix()

    def draw_all(c):
        c.set_matrix(m)
        return [fn(c) for fn in actors]
    surf, pts = Y.layer(draw_all)
    cr.restore()
    if shadow:
        Y.cast_shadow(cr, surf)
    Y.paint_layer(cr, surf)
    if dim > 0.01:
        cr.set_source_rgba(0.0, 0.0, 0.05, 0.5 * dim)
        cr.paint()
    cr.save()
    apply(cr)
    if extra:
        extra(cr, pts)
    Y.lamps(cr, t)
    cr.restore()
    Y.light(cr, t, light_strength, flash)
    if ui:
        ui(cr, pts)
    Y.finish(cr, t)
    return pts


