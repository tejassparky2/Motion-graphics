def walk(t, t0, t1, x0, x1, period=0.6, amp=0.55):
    """Stepping across the stage from x0 to x1 between t0 and t1: (x, liftL, liftR)."""
    u = clamp((t - t0) / max(0.01, t1 - t0))
    x = x0 + (x1 - x0) * (u * u * (3 - 2 * u))
    if t <= t0 or t >= t1:
        return x, 0.0, 0.0
    ph = (t - t0) / period
    f = ph % 1.0
    lift = amp * math.sin(math.pi * f)
    side = int(ph) % 2
    return x, lift if side == 0 else 0.0, lift if side == 1 else 0.0


def stamp_dust(c, foot, stamp, k=7):
    if stamp <= 0.01:
        return
    for i in range(k):
        a = math.pi * (0.1 + 0.8 * i / (k - 1))
        d = 40 + 140 * (1 - stamp)
        Y.sparkle(c, foot[0] - d * math.cos(a), foot[1] - 10 - d * 0.5 * math.sin(a), 18 * stamp, stamp)


def hearts(c, t, t0, x, y, n=4, a=1.0, spread=120):
    """Little hearts rising and fading from (x, y) after t0."""
    if t < t0 or a <= 0.01:
        return
    for i in range(n):
        u = ((t - t0) * 0.55 + i / n) % 1.0
        if t - t0 < i / n / 0.55:
            continue
        hx = x + spread * math.sin(i * 2.1) * 0.6 + 18 * math.sin(t * 2 + i)
        hy = y - 260 * u
        C.heart(c, hx, hy, 0.7 + 0.5 * (1 - u), a * clamp(u * 5) * clamp((1 - u) * 2.5))


