def compose(cr, t, actors, theme=("crimson", "sun"), zoom=(1.0, W / 2, 1150), behind=None, extra=None, ui=None,
            flash=0.0, musicians_at=None, shadow=True, sil=0.0, garland=True):
    """Y.compose with a choice of thera: theme = (style, motif) of the kit, or one of this reel's three visits
    ("bgy_brahma", "bgy_kailasa", "bgy_vaikuntha"). sil 0..1 = the shadow-play moment: the thera lit hot from behind
    and every actor a dark shadow."""
    z, zx, zy = zoom

    def apply(c):
        if z != 1.0:
            c.translate(zx, zy)
            c.scale(z, z)
            c.translate(-zx, -zy)
    cr.set_source_rgb(0.02, 0.015, 0.03)              # an opaque night first (a zoomed stage leaves no edges)
    cr.paint()
    cr.save()
    apply(cr)
    C.stage(cr, t, theme, garland)
    if sil > 0:
        C.backlight(cr, t, sil)
    if behind:
        behind(cr)
    if musicians_at is not None:
        mx, ms, mflip = musicians_at
        Y.musicians(cr, t, mx, Y.FLOOR_Y + 40, ms, mflip)
    m = cr.get_matrix()

    def draw_all(c):
        c.set_matrix(m)
        return [fn(c) for fn in actors]
    surf, pts = Y.layer(draw_all)
    cr.restore()
    if shadow and sil < 0.99:
        Y.cast_shadow(cr, surf, alpha=0.6 * (1 - sil))
    if sil < 0.999:
        Y.paint_layer(cr, surf, 1 - sil)
    C.silhouette(cr, surf, sil)
    cr.save()
    apply(cr)
    if extra:
        extra(cr, pts)
    Y.lamps(cr, t)
    cr.restore()
    Y.light(cr, t, 1.0, flash)
    if ui:
        ui(cr, pts)
    Y.finish(cr, t)
    return pts


