def feet_scene(cr, t, zoom, k, ui_fn, theme=("crimson", "sun")):
    """The hook / callback picture. k = cue times: R (the sage appears), K (soft flash and a gold footprint on
    Vishnu's chest), B (Vishnu spins down and kneels at the sage's raised foot), P (red ring, hearts)."""
    sage_in = sm(t, k["R"] - 0.1, 0.35)
    dur = 0.75
    sp = SY.spin(t, k["B"], dur)
    half = t >= k["B"] + dur / 2
    mv = sm(t, k["B"], dur)
    sway_back = prog(t, k["K"] - 0.05, 0.12) * (1 - prog(t, k["K"] + 0.45, 0.4))
    fp = prog(t, k["K"], 0.25) * (1 - prog(t, k["B"], 0.3))
