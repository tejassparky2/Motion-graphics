def sm(t, t0, dur):
    """0..1 from t0 over dur, slow in and slow out (smoothstep)."""
    u = clamp((t - t0) / max(1e-6, dur))
    return u * u * (3 - 2 * u)


def out_a(t, t_out, d=0.18):
    """1 until t_out - d, then fading to 0 at t_out."""
    return 1.0 - prog(t, t_out - d, d)


def bp(t, amp=0.6, ph=0.0, **kw):
    """A pose with the Yakshagana idle sway (shift / lean / head given in kw are added to the sway)."""
    sh, ln, hd = Y.sway(t, amp, 0.45, ph)
    p = dict(shift=sh + kw.pop("shift", 0.0), lean=ln + kw.pop("lean", 0.0), head=hd * 0.6 + kw.pop("head", 0.0),
             sash=-ln * 3, breathe=math.sin(t * 2.2 + ph), bend=0.3)
    p.update(kw)
    return p


